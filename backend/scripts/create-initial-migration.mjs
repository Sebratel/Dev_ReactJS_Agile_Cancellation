import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { backendRoot, placeholderDatabaseUrl } from './load-env.mjs';

const require = createRequire(import.meta.url);
const prismaCli = require.resolve('prisma/build/index.js');
const migrationName = process.argv[2] ?? 'init_collection_cancellation_schema';
const timestamp = new Date()
  .toISOString()
  .replace(/[-:TZ.]/g, '')
  .slice(0, 14);
const migrationDir = path.join(
  backendRoot,
  'prisma',
  'migrations',
  `${timestamp}_${migrationName}`,
);

const sql = execFileSync(
  process.execPath,
  [
    prismaCli,
    'migrate',
    'diff',
    '--from-empty',
    '--to-schema-datamodel',
    'prisma/schema.prisma',
    '--script',
  ],
  {
    cwd: backendRoot,
    encoding: 'utf8',
    env: {
      ...process.env,
      DATABASE_URL: placeholderDatabaseUrl,
    },
  },
);

fs.mkdirSync(migrationDir, { recursive: true });
fs.writeFileSync(path.join(migrationDir, 'migration.sql'), sql);

const lockPath = path.join(
  backendRoot,
  'prisma',
  'migrations',
  'migration_lock.toml',
);

if (!fs.existsSync(lockPath)) {
  fs.writeFileSync(
    lockPath,
    '# Please do not edit this file manually\n# It should be added in your version-control system (i.e. Git)\nprovider = "mysql"\n',
  );
}

process.stdout.write(
  `Migration criada em ${path.relative(backendRoot, migrationDir)}\n`,
);
